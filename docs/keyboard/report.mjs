// Full-page generator: only metric definitions and layout are maintained here.
const escape = value => String(value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

export function selectRows(rows, query, unchanged) {
	const needle = query.trim().toLowerCase();
	return rows.filter(row => (unchanged || row[4]) && (!needle || row.slice(0, 4).join(' ').toLowerCase().includes(needle)));
}

function browserMain() {
	const data = JSON.parse(document.getElementById('data').textContent);
	const search = document.getElementById('search'), unchanged = document.getElementById('unchanged');
	function render() {
		for (let index = 0; index < data.tables.length; index++) {
			const rows = selectRows(data.tables[index].rows, search.value, unchanged.checked);
			const fragment = document.createDocumentFragment();
			for (const [action, id, upstream, ours] of rows) {
				const tr = document.createElement('tr');
				for (const [column, text] of [action, upstream, ours].entries()) {
					const td = document.createElement('td');
					td.textContent = text;
					if (column === 0) td.title = id;
					tr.append(td);
				}
				fragment.append(tr);
			}
			if (!rows.length) {
				const tr = document.createElement('tr'), td = document.createElement('td');
				td.colSpan = 3; td.textContent = 'No matching shortcuts.'; tr.append(td); fragment.append(tr);
			}
			document.getElementById(`rows-${index}`).replaceChildren(fragment);
			document.getElementById(`count-${index}`).textContent = `${rows.length} actions shown`;
		}
	}
	let timer;
	search.addEventListener('input', () => { clearTimeout(timer); timer = setTimeout(render, 120); });
	unchanged.addEventListener('change', render);
	render();
}

export function packRows(rows) {
	const binding = (keys, unresolved) => [...keys, ...(unresolved ? ['Not resolved'] : [])].join(' · ') || '—';
	return rows.map(row => [row.action, row.id, binding(row.upstream, row.upstreamUnresolved),
		binding(row.ours, row.oursUnresolved), row.changed ? 1 : 0]);
}

